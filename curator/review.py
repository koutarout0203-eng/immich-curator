from __future__ import annotations

from typing import Any, Protocol


class AlbumClient(Protocol):
    def find_owned_albums(self, name: str) -> list[dict[str, Any]]: ...
    def create_album(self, name: str, description: str) -> dict[str, Any]: ...
    def add_assets_to_album(self, album_id: str, asset_ids: list[str]) -> None: ...
    def iter_album_assets(self, album_id: str): ...


def review_asset_ids(memories: dict[str, Any], event_limit: int, max_assets: int) -> list[str]:
    rows = memories.get("memories")
    if not isinstance(rows, list):
        raise ValueError("Memory JSON does not contain a memories list")
    result: list[str] = []
    seen: set[str] = set()
    for memory in rows[:event_limit]:
        if not isinstance(memory, dict):
            continue
        assets = memory.get("assets")
        if not isinstance(assets, list):
            continue
        for asset in assets:
            identifier = asset.get("id") if isinstance(asset, dict) else None
            if isinstance(identifier, str) and identifier and identifier not in seen:
                seen.add(identifier)
                result.append(identifier)
                if len(result) >= max_assets:
                    return result
    return result


def create_review_album(
    client: AlbumClient,
    memories: dict[str, Any],
    *,
    name: str,
    event_limit: int = 5,
    max_assets: int = 60,
    apply: bool = False,
) -> dict[str, Any]:
    if not name.strip():
        raise ValueError("Review album name must not be empty")
    asset_ids = review_asset_ids(memories, event_limit, max_assets)
    plan = {
        "mode": "apply" if apply else "dry-run",
        "album_name": name,
        "event_limit": event_limit,
        "asset_count": len(asset_ids),
        "asset_ids": asset_ids,
    }
    if not apply:
        return plan
    if not asset_ids:
        raise ValueError("Refusing to create an empty review album")

    existing = client.find_owned_albums(name)
    if len(existing) > 1:
        raise ValueError(f"Multiple owned albums have the name {name!r}")
    album = existing[0] if existing else client.create_album(
        name,
        "Generated by Immich Curator for manual review. Assets and visibility are unchanged.",
    )
    album_id = album.get("id")
    if not isinstance(album_id, str) or not album_id:
        raise ValueError("Album response has no id")
    client.add_assets_to_album(album_id, asset_ids)
    present = {
        asset.get("id")
        for asset in client.iter_album_assets(album_id)
        if isinstance(asset, dict) and asset.get("id")
    }
    missing = [identifier for identifier in asset_ids if identifier not in present]
    if missing:
        raise ValueError(f"Album verification failed: {len(missing)} assets missing")
    return {**plan, "album_id": album_id, "verified": True}
